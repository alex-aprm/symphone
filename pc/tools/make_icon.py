"""Builds the Symphone icon: a phone with a treble (G) clef.

    python tools/make_icon.py <NotoMusic-Regular.ttf>

Writes phonesync/ui/icon.svg (master), icon.png (256 px), icon.ico (16-256 px) and the Android launcher vector
(android/app/src/main/res: adaptive ic_launcher). The clef outline comes from Noto Music (SIL Open Font
License 1.1, https://github.com/notofonts/music). PNG rendering uses headless Microsoft Edge.
"""
import pathlib
import subprocess
import sys
import tempfile

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parents[2]
UI = ROOT / "pc" / "phonesync" / "ui"
EDGE = r"C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe"

BG_FROM, BG_TO = "#6d5dfc", "#0ea5e9"


def clef(font_path: str):
    f = TTFont(font_path)
    gs = f.getGlyphSet()
    g = f.getBestCmap()[0x1D11E]
    bp = BoundsPen(gs)
    gs[g].draw(bp)
    pen = SVGPathPen(gs)
    gs[g].draw(pen)
    return pen.getCommands(), bp.bounds


def layout(bounds, height=146.0, cx=128.0, cy=134.0):
    x0, y0, x1, y1 = bounds
    s = height / (y1 - y0)
    return cx - s * (x0 + x1) / 2, cy + s * (y0 + y1) / 2, s       # translate x, y; scale (y flipped)


def svg(d, bounds) -> str:
    tx, ty, s = layout(bounds)
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256" width="256" height="256">
  <!-- Symphone: a phone with a treble (G) clef. Clef outline: Noto Music, SIL Open Font License 1.1. -->
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="{BG_FROM}"/>
      <stop offset="1" stop-color="{BG_TO}"/>
    </linearGradient>
    <linearGradient id="glass" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#ffffff" stop-opacity=".22"/>
      <stop offset="1" stop-color="#ffffff" stop-opacity=".08"/>
    </linearGradient>
  </defs>
  <rect x="8" y="8" width="240" height="240" rx="56" fill="url(#bg)"/>
  <rect x="74" y="30" width="108" height="196" rx="24" fill="url(#glass)" stroke="#fff" stroke-width="9"/>
  <rect x="113" y="44" width="30" height="6" rx="3" fill="#fff" opacity=".85"/>
  <g transform="translate({tx:.2f} {ty:.2f}) scale({s:.5f} {-s:.5f})">
    <path fill="#fff" d="{d}"/>
  </g>
</svg>
'''


def android_icon(d, bounds) -> dict[str, str]:
    """Adaptive launcher icon: gradient background + phone and clef foreground (in the 66 dp safe zone of the
    108 dp canvas; the foreground doubles as the monochrome layer for themed icons)."""
    tx, ty, s = layout(bounds)
    k, off = 66 / 196, (108 - 66) / 2          # the artwork's phone (196 units tall) fills the safe zone
    head = '<?xml version="1.0" encoding="utf-8"?>\n<!-- generated by pc/tools/make_icon.py -->\n'
    bg = head + f'''<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="0" android:startY="0" android:endX="108" android:endY="108">
                <item android:offset="0" android:color="#FF{BG_FROM[1:]}"/>
                <item android:offset="1" android:color="#FF{BG_TO[1:]}"/>
            </gradient>
        </aapt:attr>
    </path>
</vector>
'''
    fg = head + f'''<!-- Clef outline: Noto Music, SIL Open Font License 1.1. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <group android:translateX="{off - 74 * k + (66 - 108 * k) / 2:.3f}" android:translateY="{off - 30 * k:.3f}"
        android:scaleX="{k:.5f}" android:scaleY="{k:.5f}">
        <path android:pathData="M98,34.5 h60 a19.5,19.5 0 0 1 19.5,19.5 v148 a19.5,19.5 0 0 1 -19.5,19.5 h-60 a19.5,19.5 0 0 1 -19.5,-19.5 v-148 a19.5,19.5 0 0 1 19.5,-19.5 z"
            android:fillColor="#00000000" android:strokeColor="#FFFFFFFF" android:strokeWidth="9"/>
        <path android:pathData="M116,44 h24 a3,3 0 0 1 0,6 h-24 a3,3 0 0 1 0,-6 z" android:fillColor="#FFFFFFFF"/>
        <group android:translateX="{tx:.2f}" android:translateY="{ty:.2f}" android:scaleX="{s:.5f}" android:scaleY="{-s:.5f}">
            <path android:fillColor="#FFFFFFFF" android:pathData="{d}"/>
        </group>
    </group>
</vector>
'''
    adaptive = head + '''<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_bg"/>
    <foreground android:drawable="@drawable/ic_launcher_fg"/>
    <monochrome android:drawable="@drawable/ic_launcher_fg"/>
</adaptive-icon>
'''
    return {"drawable/ic_launcher_bg.xml": bg, "drawable/ic_launcher_fg.xml": fg,
            "mipmap-anydpi-v26/ic_launcher.xml": adaptive}


def render_png(svg_path: pathlib.Path, out: pathlib.Path, size: int = 256):
    with tempfile.TemporaryDirectory() as prof:
        page = pathlib.Path(prof) / "icon.html"
        page.write_text(f'<html><body style="margin:0;background:transparent"><img src="{svg_path.as_uri()}" '
                        f'style="display:block;width:{size}px;height:{size}px"></body></html>', "utf-8")
        subprocess.run([EDGE, "--headless=new", "--disable-gpu", "--hide-scrollbars", "--default-background-color=00000000",
                        "--allow-file-access-from-files", f"--window-size={size},{size}", "--force-device-scale-factor=1",
                        f"--user-data-dir={pathlib.Path(prof) / 'profile'}", f"--screenshot={out}", page.as_uri()],
                       check=True, capture_output=True, timeout=60)
    Image.open(out).convert("RGBA").resize((size, size), Image.LANCZOS).save(out)


def main():
    d, bounds = clef(sys.argv[1])
    master = UI / "icon.svg"
    master.write_text(svg(d, bounds), "utf-8")
    big = ROOT / "docs" / "icon.png"
    render_png(master, big, 512)
    img = Image.open(big)
    img.resize((256, 256), Image.LANCZOS).save(UI / "icon.png")
    img.save(UI / "icon.ico", sizes=[(256, 256), (128, 128), (64, 64), (48, 48), (32, 32), (24, 24), (16, 16)])
    res = ROOT / "android" / "app" / "src" / "main" / "res"
    for name, text in android_icon(d, bounds).items():
        (res / name).parent.mkdir(parents=True, exist_ok=True)
        (res / name).write_text(text, "utf-8")
    print("icon written")


if __name__ == "__main__":
    main()
